import {expect,test} from '@playwright/test';

test.use({baseURL:process.env.DEMO_BASE_URL||'http://localhost:3000'});

test('demo tour has Bot controls, advances on blank space, and stays inside modal dialogs',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 let starts=0;
 await page.route('**/api/v1/auth/me',route=>route.fulfill({json:{id:'tour-judge',email:'judge@example.test',role:'STEWARD',csrf_token:'test-token',capabilities:['read','explain'],demo:{run_id:null,state:'NEW',dataset_version:'test',expires_at_epoch:9999999999}}}));
 await page.route('**/api/v1/mdm/demo/catalog',route=>route.fulfill({json:{version:'test',title:'Dữ liệu mẫu',description:'Dữ liệu giả lập',record_count:2000,file_count:4,synthetic:true,files:[]}}));
 await page.route('**/api/v1/mdm/demo/start',route=>{starts++;return route.fulfill({json:{run_id:'test',status:'READY'}});});
 await page.setViewportSize({width:1380,height:950});
 await page.goto('/app/demo');
 const bot=page.getByRole('region',{name:'Trò chuyện với Master Bot'});
 await expect(bot.getByRole('button',{name:'Tiếp theo',exact:true})).toBeVisible();
 await expect(bot).toContainText('bốn tệp dữ liệu mẫu',{timeout:10000});
 await bot.getByRole('button',{name:'Tiếp theo',exact:true}).click();
 await expect(bot).toContainText('Khi sẵn sàng',{timeout:10000});
 await page.locator('main').click({position:{x:4,y:4}});
 await expect(bot).toContainText('Bạn đã xem các gợi ý',{timeout:10000});
 await expect(bot.getByRole('button',{name:'Xem lại hướng dẫn'})).toBeVisible();
 expect(starts).toBe(0);
 await page.getByRole('button',{name:'Bỏ qua hướng dẫn',exact:true}).click();
 await expect(bot).toBeHidden();
 await page.locator('main').click({position:{x:4,y:4}});
 await expect(bot).toBeHidden();
 await page.getByRole('button',{name:'Chạy hướng dẫn',exact:true}).click();
 await expect(bot.getByRole('button',{name:'Tiếp theo',exact:true})).toBeVisible();
 await expect(page.getByRole('region',{name:'Gợi ý trải nghiệm'})).toContainText('Chọn cách trải nghiệm');
 await page.waitForTimeout(350);
 const target=await page.locator('[data-demo="demo-embedding"]').boundingBox();
 const ring=await page.locator('[class*="guideRing"]').boundingBox();
 expect(target).not.toBeNull();expect(ring).not.toBeNull();
 expect(Math.abs(ring!.x-(target!.x-4))).toBeLessThan(2);
 expect(Math.abs(ring!.width-(target!.width+8))).toBeLessThan(2);
 await page.screenshot({path:info.outputPath('guide-desktop.png'),fullPage:true,animations:'disabled'});
 await page.setViewportSize({width:390,height:844});
 await expect(bot.getByRole('button',{name:'Tiếp theo',exact:true})).toBeInViewport();
 await expect(page.getByRole('button',{name:'Bỏ qua hướng dẫn',exact:true})).toBeInViewport();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.waitForTimeout(350);
 await page.screenshot({path:info.outputPath('guide-mobile.png'),fullPage:true,animations:'disabled'});
 await page.setViewportSize({width:1380,height:950});
 await page.evaluate(()=>{
  const dialog=document.createElement('dialog');dialog.setAttribute('aria-label','Kiểm tra hướng dẫn trong bảng');
  dialog.style.cssText='width:700px;height:320px;padding:30px';
  dialog.innerHTML='<div data-demo="pair-comparison">Hồ sơ khách hàng</div><button data-demo="comparison-close">Đóng bảng</button>';
  dialog.addEventListener('mousedown',event=>{if(event.target===dialog)dialog.close();});
  document.body.append(dialog);dialog.showModal();
 });
 const dialog=page.getByRole('dialog',{name:'Kiểm tra hướng dẫn trong bảng'});
 await expect(dialog.getByRole('button',{name:'Tiếp theo',exact:true})).toBeVisible();
 await expect(bot).toContainText('Đây là thông tin thực tế',{timeout:10000});
 await page.mouse.click(8,500);
 await expect(dialog).toBeVisible();
 await expect(bot).toContainText('Khi đã xem xong',{timeout:10000});
 expect(starts).toBe(0);expect(errors).toEqual([]);
});

test('the header can start guidance for a normal account without entering demo',async({page},info)=>{
 let demoStarts=0;
 await page.route('**/api/v1/auth/me',route=>route.fulfill({json:{id:'normal-guide',email:'user@example.test',role:'STEWARD',csrf_token:'test-token',capabilities:['read','create_run','explain'],demo:null}}));
 await page.route('**/api/v1/mdm/runs?*',route=>route.fulfill({json:{items:[],total:0,limit:25,offset:0,next_cursor:null}}));
 await page.route('**/api/v1/mdm/demo/start',route=>{demoStarts++;return route.fulfill({json:{run_id:'not-used'}});});
 await page.setViewportSize({width:1380,height:950});
 await page.goto('/app');
 const trigger=page.getByRole('button',{name:'Chạy hướng dẫn',exact:true});
 await expect(trigger).toBeVisible();
 await trigger.click();
 const bot=page.getByRole('region',{name:'Trò chuyện với Master Bot'});
 await expect(bot.getByRole('button',{name:'Tiếp theo',exact:true})).toBeVisible();
 await expect(bot).toContainText('Tổng quan',{timeout:10000});
 await expect(page.getByText('Phiên demo',{exact:true})).toHaveCount(0);
 await page.screenshot({path:info.outputPath('header-guide-desktop.png'),fullPage:true,animations:'disabled'});
 await page.setViewportSize({width:390,height:844});
 await expect(trigger).toBeInViewport();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('header-guide-mobile.png'),fullPage:true,animations:'disabled'});
 expect(demoStarts).toBe(0);
});
