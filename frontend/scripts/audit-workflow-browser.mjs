import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const out = 'artifacts/audit-20261012';
await mkdir(out, {recursive:true});
const browser = await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const login = await context.request.post('http://localhost:8001/api/v1/auth/login',{headers:{Origin:'http://localhost:3000'},data:{email:process.env.AUDIT_EMAIL,password:process.env.AUDIT_PASSWORD}});
if (!login.ok()) throw new Error('Browser login failed');
const page = await context.newPage(); page.setDefaultTimeout(60000); const errors=[]; const checks=[];
page.on('pageerror',error => errors.push(error.message));
const run = process.env.AUDIT_RUN, smoke = process.env.AUDIT_SMOKE_RUN;
try {
await page.goto(`http://localhost:3000/app/sessions/${run}/decisions`);
await page.getByRole('heading',{name:'Phân loại các cặp bản ghi',exact:true}).waitFor();
await page.getByRole('checkbox',{name:'Chọn trang hiện tại',exact:true}).check();
await page.getByRole('button',{name:'Chọn toàn bộ bộ lọc',exact:true}).click();
await page.getByText(/Đã chọn toàn bộ bộ lọc/).waitFor();
checks.push('pairs_page_all_selection');
await page.screenshot({path:`${out}/desktop-decisions.png`,fullPage:true});
await page.getByRole('button',{name:'Bỏ chọn',exact:true}).click();
await page.getByRole('button',{name:/Giải thích bằng AI cặp/}).first().click();
await page.getByText(/Giải thích từ AI|Giải thích theo quy tắc/).first().waitFor({timeout:45000});
checks.push('provider_or_explicit_fallback_rendered');
await page.goto(`http://localhost:3000/app/sessions/${smoke}/golden`);
await page.getByText('FINALIZED',{exact:true}).first().waitFor();
await page.screenshot({path:`${out}/desktop-golden.png`,fullPage:true});
checks.push('official_golden_after_reload');
await page.goto(`http://localhost:3000/app/uploads/new`);
await page.getByRole('heading',{name:'Chuẩn bị dữ liệu',exact:true}).waitFor();
const first=Buffer.from('record_id,source,name,phone,email,address\n1,CRM,Ada,0901234567,a@example.test,Hanoi\n');
const second=Buffer.from('record_id,source,name,phone,email,address\n2,BILL,Ada,0901234567,a@example.test,Hanoi\n');
await expect(page.getByLabel('Chọn các file CSV',{exact:true})).toBeEnabled({timeout:60000});
await page.getByLabel('Chọn các file CSV',{exact:true}).setInputFiles([{name:'browser-first.csv',mimeType:'text/csv',buffer:first}]);
await page.getByLabel('Thêm các file CSV',{exact:true}).waitFor({state:'attached'});
await expect(page.getByLabel('Thêm các file CSV',{exact:true})).toBeEnabled({timeout:60000});
await page.getByLabel('Thêm các file CSV',{exact:true}).setInputFiles([{name:'browser-second.csv',mimeType:'text/csv',buffer:second}]);
await page.getByText('browser-second.csv',{exact:true}).waitFor({timeout:60000});
await expect(page.getByRole('button',{name:'Tạo phiên từ dữ liệu đã kiểm tra',exact:true})).toBeEnabled({timeout:120000});
await page.screenshot({path:`${out}/desktop-added-files.png`,fullPage:true});
checks.push('draft_add_files_real_upload');
await page.setViewportSize({width:390,height:844});
await page.goto(`http://localhost:3000/app/sessions/${run}/decisions`);
await page.getByRole('checkbox',{name:'Chọn trang hiện tại',exact:true}).waitFor();
const fits=await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
if (!fits) throw new Error('Mobile page overflows horizontally');
await page.screenshot({path:`${out}/mobile-decisions.png`,fullPage:true});
checks.push('mobile_390_no_page_overflow');
await writeFile(`${out}/browser.json`,JSON.stringify({checks,errors},null,2));
await browser.close();
if (errors.length) throw new Error('Browser JavaScript errors');
console.log('Browser audit passed:',checks.join(', '));
} catch (error) {
  await page.screenshot({path:`${out}/browser-failure.png`,fullPage:true}).catch(()=>{});
  await writeFile(`${out}/browser-failure.json`,JSON.stringify({checks,errors,text:await page.locator('body').innerText()},null,2));
  await browser.close();
  throw error;
}
