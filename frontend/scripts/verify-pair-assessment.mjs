import {chromium,expect as baseExpect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const expect=baseExpect.configure({timeout:60000});
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
const out='artifacts/pair-review-compact-20261012';
await mkdir(out,{recursive:true});
const checks={},errors=[],reads=[];
try {
  const context=await browser.newContext({viewport:{width:1440,height:1100}});
  await context.addCookies([{name:'masterone_session',value:process.env.PAIR_ASSESSMENT_TOKEN,url:'http://localhost:3000',httpOnly:true,sameSite:'Lax'}]);
  const page=await context.newPage();page.setDefaultTimeout(60000);
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(request.method()==='GET'&&request.url().includes('/workflow/pairs?'))reads.push(request.url());});
  await page.goto(`http://localhost:3000/app/sessions/${process.env.PAIR_ASSESSMENT_RUN}/decisions`);
  await expect(page.getByRole('button',{name:'Đánh giá lại bằng chứng'})).toBeHidden();
  checks.assessment_tools_collapsed=true;
  await page.getByText('Công cụ đánh giá',{exact:true}).click();
  await expect(page.getByRole('heading',{name:'Đánh giá bằng chứng mới',exact:true})).toBeVisible();
  const table=page.getByRole('table',{name:'Danh sách cặp bản ghi',exact:true});
  await expect(table.locator('tbody tr')).toHaveCount(10);
  checks.ten_pairs=true;
  await expect(page.getByRole('option',{name:'Chưa phân nhóm',exact:true})).toHaveCount(0);
  checks.no_unclassified=true;
  await expect(page.getByText('Mô hình đã kiểm định trên dữ liệu tổng hợp; chưa được chứng nhận cho dữ liệu thực tế.',{exact:true})).toBeVisible();
  checks.synthetic_scope_disclosed=true;
  await page.getByText('Công cụ đánh giá',{exact:true}).click();
  await expect(page.getByRole('button',{name:'Đánh giá lại bằng chứng'})).toBeHidden();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:`${out}/initial.png`});
  const top=await table.boundingBox();
  expect(top.y).toBeLessThan(760);checks.pairs_visible_without_long_intro=true;
  await page.getByText('Hiểu Group/Subgroup và Accept/Deny',{exact:true}).click();
  await expect(page.getByText(/Deny ngăn hai bản ghi cùng nhóm/)).toBeVisible();
  await page.getByText('Hiểu Group/Subgroup và Accept/Deny',{exact:true}).click();
  checks.group_guide_accessible=true;
  const groups=(await page.getByRole('combobox',{name:'Group',exact:true}).locator('option').evaluateAll(options=>options.map(o=>o.value))).filter(v=>v&&v!=='UNCLASSIFIED');
  const group=page.getByRole('combobox',{name:'Group',exact:true});
  async function selectReady(key){await group.selectOption(key);await expect(table.locator('tbody tr td:nth-child(3)').first()).toContainText(`Group ${key}`);await expect(table.locator('xpath=ancestor::section[1]')).toHaveAttribute('aria-busy','false');}
  for(const key of groups.slice(0,2))await selectReady(key);
  await selectReady(groups[0]);
  const visits=()=>reads.filter(url=>new URL(url).searchParams.get('group')===groups[0]&&Number(new URL(url).searchParams.get('offset'))===0).length;
  const before=visits();
  await selectReady(groups[1]);await selectReady(groups[0]);await page.waitForTimeout(800);
  expect(visits()).toBe(before);
  checks.group_cache_reused=true;
  await group.selectOption('');await expect(table.locator('tbody tr')).toHaveCount(10);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:`${out}/desktop.png`,fullPage:true});
  await page.screenshot({path:`${out}/desktop-viewport.png`});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  checks.no_mobile_page_overflow=true;
  await page.screenshot({path:`${out}/mobile.png`,fullPage:true});
  await page.getByRole('button',{name:/Chọn trang này/}).click();
  await page.getByRole('button',{name:'Accept theo phạm vi'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button',{name:'Hủy',exact:true}).click();
  checks.mobile_bulk_preview_accessible=true;
  expect(errors).toEqual([]);checks.no_browser_errors=true;
  await writeFile(`${out}/browser.json`,JSON.stringify({checks,errors,pair_reads:reads.length},null,2));
  console.log(JSON.stringify(checks));
} finally {await browser.close();}
