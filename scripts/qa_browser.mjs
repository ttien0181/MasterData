// Real production Next frontend + Docker API. No route mocks or live cloud keys.
import { chromium } from '../frontend/node_modules/@playwright/test/index.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const output = path.resolve(process.argv.includes('--output') ? process.argv[process.argv.indexOf('--output') + 1] : 'artifacts/full-system-20261009/browser-live');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const context = await browser.newContext({ acceptDownloads: true });
const page = await context.newPage();
const errors = [], failed = [], responses = [];
page.on('pageerror', error => errors.push({ type: error.name }));
page.on('requestfailed', request => failed.push({ path: new URL(request.url()).pathname, error: request.failure()?.errorText }));
page.on('response', response => {
  if (new URL(response.url()).port === '18001') responses.push({path: new URL(response.url()).pathname, status: response.status()});
});
const result = { scope: 'real Docker frontend/API, synthetic data, no LLM generation', cases: [] };
let phase = 'login';
try {
  await page.goto('http://127.0.0.1:13000/login');
  await page.locator('#email').fill('qa-steward@example.com');
  await page.locator('#password').fill('local-qa-synthetic-password');
  await page.locator('button[type=submit]').click();
  await page.waitForURL('**/app', { timeout: 20000 });
  result.cases.push({ name: phase, status: 'PASS' });
  phase = 'discover_workspace';
  await page.waitForLoadState('networkidle');
  result.buttons = await page.getByRole('button').allTextContents();
  result.file_inputs = await page.locator('input[type=file]').count();
  await page.screenshot({ path: path.join(output, 'workspace.png'), fullPage: true });
  result.cases.push({ name: phase, status: 'PASS' });
  phase = 'upload_csv_and_start_worker';
  await page.getByRole('button', { name: '＋ Nạp dữ liệu', exact: true }).click();
  const content = 'record_id,source,name,phone,email,dob,address\na,CRM,Nguyễn Văn An,0901234567,qa@example.com,1990-01-01,12 phố Huế Hà Nội\nb,ERP,Nguyễn Văn An,+84901234567,qa@example.com,1990-01-01,12 phố Huế Hà Nội\nc,BILL,Trần Thị Lan,0907654321,qc@example.com,1980-01-01,20 phố Huế Hà Nội\nd,CRM,Lê Văn Hùng,0981234567,,1980-01-01,\ne,ERP,Phạm Thị Bích,0981234567,,1980-01-01,\nf,CRM,Trần Thị Hoa,,review-c@example.com,,\ng,ERP,Trần Hoa,,review-c@example.com,,\n';
  await page.getByLabel('Chọn các file CSV').setInputFiles({ name: 'browser-qa.csv', mimeType: 'text/csv', buffer: Buffer.from(content) });
  const startButton = page.getByRole('button', { name: 'Bắt đầu phân giải', exact: true });
  await startButton.waitFor({ timeout: 30000 });
  const started = page.waitForResponse(r => /\/runs\/[^/]+\/start$/.test(r.url()) && r.status() === 202, { timeout: 30000 });
  await startButton.click();
  const startResponse = await started;
  result.run_id = new URL(startResponse.url()).pathname.split('/').at(-2);
  const task = await startResponse.json();
  const taskId = task.task_id ?? task.id;
  let completed = false;
  const until = Date.now() + 180000;
  while (Date.now() < until) {
    const response = await page.request.get(`http://127.0.0.1:18001/api/v1/mdm/runs/tasks/${taskId}`);
    if (response.status() !== 200) throw new Error('Task lookup failed');
    const state = await response.json();
    if (state.status === 'COMPLETED') { completed = true; break; }
    if (['FAILED','RETRYABLE_FAILED','CANCELLED'].includes(state.status)) throw new Error('Worker task failed');
    await new Promise(resolve => setTimeout(resolve, 1000));
  }
  if (!completed) throw new Error('Worker did not complete before timeout');
  await page.reload();
  await page.waitForLoadState('networkidle');
  result.cases.push({ name: phase, status: 'PASS', run_id: result.run_id });
  phase = 'review_reject_then_approve';
  await page.getByRole('button', { name: 'Cần xem xét', exact: true }).click();
  const rejectedRow = page.locator('.pair-list-table tbody tr').filter({ hasText: 'Phạm Thị Bích' }).first();
  await rejectedRow.getByRole('button', { name: /^So sánh cặp / }).click();
  let responsePromise = page.waitForResponse(r => /\/review-pairs\/[^/]+\/decision$/.test(r.url()));
  await page.getByRole('button', { name: 'Xác nhận không gộp', exact: true }).click();
  if ((await responsePromise).status() !== 200) throw new Error('Steward reject failed');
  const approvedRow = page.locator('.pair-list-table tbody tr').filter({ hasText: 'Trần Thị Hoa' }).first();
  await approvedRow.getByRole('button', { name: /^So sánh cặp / }).click();
  responsePromise = page.waitForResponse(r => /\/review-pairs\/[^/]+\/decision$/.test(r.url()));
  await page.getByRole('button', { name: 'Xác nhận gộp', exact: true }).click();
  if ((await responsePromise).status() !== 200) throw new Error('Steward approve failed');
  result.cases.push({ name: phase, status: 'PASS' });
  phase = 'merge_workspace';
  await page.getByRole('button', { name: 'Tự động gộp', exact: true }).click();
  await page.waitForLoadState('networkidle');
  result.merge_buttons = await page.getByRole('button').allTextContents();
  const itemsResponse = await page.request.get(`http://127.0.0.1:18001/api/v1/mdm/runs/${result.run_id}/items/merge`);
  const items = await itemsResponse.json();
  if (items.total !== 2) throw new Error('Expected one automatic and one steward-approved proposal');
  result.merge_item_id = items.items[0].id;
  result.merge_count = items.total;
  phase = 'golden_field_selection';
  await page.locator('.resolution-item-open').filter({ hasText: 'Nguyễn Văn An' }).first().click();
  await page.getByRole('heading', { name: /Nguyễn Văn An/ }).waitFor();
  const radio = page.locator('input[name="field-phone"]:not(:checked)').first();
  if (await radio.count() === 0) throw new Error('Fixture must offer alternative raw phone values');
  result.golden_phone_choice_external_id = (await radio.locator('..').locator('.resolution-source').first().textContent()).split('·').at(-1).trim();
  await radio.check();
  await page.getByRole('button', { name: 'Lưu lựa chọn', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Đóng', exact: true }).first().click();
  // The approved pair has conflicting raw names: explicitly choose its golden
  // value as required by export readiness, keeping the product guard intact.
  await page.locator('.resolution-item-open').filter({ hasText: 'Trần Thị Hoa' }).first().click();
  await page.getByRole('heading', { name: /Trần Thị Hoa/ }).waitFor();
  await page.locator('input[name="field-name"]:not(:checked)').first().check();
  await page.getByRole('button', { name: 'Lưu lựa chọn', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Đóng', exact: true }).first().click();
  result.cases.push({ name: phase, status: 'PASS' });
  await page.screenshot({ path: path.join(output, 'merge.png'), fullPage: true });
  phase = 'preview_execute_download';
  await page.getByRole('button', { name: 'Xem trước CSV kết quả →', exact: true }).click();
  const acknowledge = page.getByRole('button', { name: 'Tiếp tục xem trước', exact: true });
  if (await acknowledge.isVisible()) await acknowledge.click();
  await page.getByRole('heading', { name: 'Xem trước CSV kết quả', exact: true }).waitFor();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Xác nhận gộp và xuất CSV', exact: true }).click();
  const download = await downloadPromise;
  await download.saveAs(path.join(output, 'browser-export.csv'));
  if (await download.failure()) throw new Error('Export download failed');
  result.cases.push({ name: phase, status: 'PASS', file: 'browser-export.csv' });
  phase = 'refresh_export_history';
  await page.reload();
  await page.getByRole('button', { name: 'Lịch sử xuất', exact: true }).click();
  await page.waitForLoadState('networkidle');
  result.cases.push({ name: phase, status: 'PASS' });
  phase = 'selective_split_preview_execute';
  await page.getByRole('button', { name: 'Tách bản ghi', exact: true }).click();
  await page.getByRole('button', { name: /^Tách CRM/ }).first().click();
  await page.getByRole('heading', { name: 'Xem trước khi tách', exact: true }).waitFor();
  const splitResponse = page.waitForResponse(r => /\/merges\/[^/]+\/split$/.test(r.url()) && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Xác nhận tách và tạo CSV mới', exact: true }).click();
  const split = await splitResponse;
  if (split.status() !== 200) throw new Error('Split failed');
  const splitPayload = await split.json();
  if (splitPayload.row_count !== 6) throw new Error('Split did not preserve other merges and input coverage');
  result.split_export_id = splitPayload.export_id;
  result.cases.push({ name: phase, status: 'PASS', output_rows: splitPayload.row_count });
  phase = 'audit_after_split';
  await page.getByRole('button', { name: 'Audit', exact: true }).click();
  await page.waitForLoadState('networkidle');
  result.cases.push({ name: phase, status: 'PASS' });
} catch (error) {
  result.cases.push({ name: phase, status: 'FAIL', error_type: error.name,
    diagnostic: error.message.split('\n').slice(0, 3).join(' ').slice(0, 500) });
} finally {
  result.final_url = page.url();
  result.final_buttons = await page.getByRole('button').allTextContents();
  await page.screenshot({ path: path.join(output, 'final-state.png'), fullPage: true });
  result.console_errors = errors; result.failed_requests = failed; result.api_responses = responses;
  await writeFile(path.join(output, 'results.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
  await browser.close();
}
process.exitCode = result.cases.some(item => item.status === 'FAIL') ? 1 : 0;
